let customScenarioResolver: ((id: string) => ScenarioConfig | undefined) | null = null;

export function registerCustomScenarioResolver(resolver: ((id: string) => ScenarioConfig | undefined) | null): void {
  customScenarioResolver = resolver;
}

export function getScenarioById(id: string): ScenarioConfig | undefined {
  const builtin = SCENARIOS.find(s => s.id === id);
  if (builtin) return builtin;
  if (customScenarioResolver) {
    return customScenarioResolver(id);
  }
  return undefined;
}

export function getScenariosByCategory(category: string, customScenarios?: ScenarioConfig[]): ScenarioConfig[] {
  const pool = customScenarios ? [...customScenarios, ...SCENARIOS] : SCENARIOS;
  if (category === 'all') return pool;
  if (category === 'aimlab') return pool.filter(s => s.id.startsWith('aimlab-'));
  if (category === 'kovaaks') return pool.filter(s => s.id.startsWith('kovaaks-'));
  return pool.filter(s => s.category === category);
}

